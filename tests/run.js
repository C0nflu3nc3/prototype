/*
 * Run all tests:            node tests/run.js
 * Regenerate data/embedded.js (file:// copies of the JSON files) first:
 *                           node tests/run.js --sync
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const read = rel => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const harness = require('./harness');
const core = require('../app.js');

const data = {
  catalog: JSON.parse(read('data/catalog.v1.json')),
  en: JSON.parse(read('i18n/en.json')),
  kk: JSON.parse(read('i18n/kk.json'))
};

function embeddedSource(d) {
  return '/* GENERATED by `node tests/run.js --sync` from data/catalog.v1.json and i18n/*.json. Do not edit by hand. */\n' +
    'window.WELLMATCH_EMBEDDED = ' + JSON.stringify(d).replace(/</g, '\\u003c') + ';\n';
}

if (process.argv.includes('--sync')) {
  fs.writeFileSync(path.join(ROOT, 'data/embedded.js'), embeddedSource(data), 'utf8');
  console.log('data/embedded.js regenerated.');
}

const FILES = ['matching', 'validate', 'i18n', 'catalog', 'state', 'testlog', 'analytics'];
for (const f of FILES) require(`./${f}.test.js`);

const results = harness.runAll({ core, data, node: true, read, embeddedSource });

let current = null;
for (const r of results) {
  if (r.file !== current) { current = r.file; console.log('\n' + current); }
  const mark = r.status === 'pass' ? '  ✓' : r.status === 'skip' ? '  -' : '  ✗';
  console.log(`${mark} ${r.name}${r.status === 'fail' ? '\n      ' + r.message : ''}`);
}
const count = s => results.filter(r => r.status === s).length;
console.log(`\n${count('pass')} passed, ${count('fail')} failed, ${count('skip')} skipped\n`);
process.exitCode = count('fail') ? 1 : 0;
